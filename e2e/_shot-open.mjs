import { boot } from './lib.mjs';
const { base, api, page, ctx, check, finish } = await boot();
const shots = 'D:\\Peblo\\_shots';
const n = (await api('POST', '/api/notes', { title: 'Plan for Friday 6 November', content: '## Today\n\n- Nothing planned yet\n\n## Still to pick\n\n- [ ] task1' })).note;
const p2 = await ctx.newPage();
await p2.routeWebSocket(/\/(yjs|collab|ws)/i, () => {});
await p2.goto(base + '/notes/' + n.id, { waitUntil: 'domcontentloaded' });
await p2.getByTestId('note-preview').waitFor({ timeout: 15000 });
await p2.screenshot({ path: shots + '\\open-preview.png' });
await p2.close();
await page.goto(base + '/notes/' + n.id, { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
await page.screenshot({ path: shots + '\\rail-min.png' });
await page.getByText('Linked tasks').first().click();
await page.waitForTimeout(400);
await page.screenshot({ path: shots + '\\rail-open.png' });
const sw = await page.evaluate(() => { const a = document.querySelector('.s-note-side'); return [a.scrollWidth, a.clientWidth]; });
check('the rail does not scroll sideways', sw[0] <= sw[1], sw.join('>'));
await finish();
