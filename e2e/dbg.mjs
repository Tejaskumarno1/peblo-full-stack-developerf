import { boot, REPO } from './lib.mjs';
const { base, api, page, finish } = await boot();
const doc = (await api('POST', '/api/notes', { title: 'Dbg', content: 'hello\n\n```js\nconst x = 1;\n```\n', tags: ['b3'] })).note;
page.on('pageerror', (e) => console.log('pageerror:', String(e).slice(0, 300)));
await page.goto(base + `/notes/${doc.id}`);
await page.locator('.bn-editor').waitFor({ timeout: 12000 });
await page.waitForTimeout(800);
await page.locator('.bn-editor p, .bn-editor .bn-inline-content').first().click();
await page.keyboard.press('Control+End');
await page.keyboard.press('Enter');
await page.keyboard.type('/templ', { delay: 60 });
await page.waitForTimeout(800);
console.log(await page.evaluate(() => [...document.querySelectorAll('[class*="suggestion"], [role="listbox"], [role="menu"]')].map((e) => e.className + '|' + e.textContent.slice(0, 80))));
await page.screenshot({ path: REPO + '/.shots/dbg-slash.png' });
