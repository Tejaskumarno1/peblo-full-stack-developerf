// Peblo right-click menu: notes in the list, links, empty space; Shift and the editor keep the browser's own menu.
import { boot } from './lib.mjs';
const { base, api, page, ctx, check, finish } = await boot({ freshPresence: true });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
try {
  await ctx.grantPermissions(['clipboard-read', 'clipboard-write']);
  const a = (await api('POST', '/api/notes', { title: 'Menu target note', content: 'Some words here.\n\n![pic](/api/media/abcdef0123456789abcdef0123456789)\n', tags: [] })).note;
  await page.setViewportSize({ width: 1400, height: 900 });
  await page.goto(`${base}/notes/${a.id}`);
  await page.locator('.bn-editor').waitFor({ timeout: 25000 });
  await wait(1500);
  const row = page.locator(`a[href="/notes/${a.id}"]`).first();
  await row.waitFor({ timeout: 10000 });
  await row.click({ button: 'right' }); await wait(600);
  check('1 right-clicking a note in the list opens the Peblo menu', (await page.locator('[data-testid="app-menu"][data-kind="note"]').count()) === 1);
  const names = await page.locator('[data-testid="app-menu"] > button').allInnerTexts();
  const need = ['Open', 'Open in new tab', 'Open in new window', 'Open as', 'New note here', 'Pin', 'Duplicate', 'Copy link', 'Save as', 'Inspect (details)', 'Move to Trash'];
  check('2 it offers the planned items', need.every((n) => names.some((x) => x.startsWith(n))), JSON.stringify(names));
  const box = await page.locator('[data-testid="app-menu"]').boundingBox();
  check('3 the menu stays inside the window', box && box.x >= 0 && box.y >= 0 && box.x + box.width <= 1400 && box.y + box.height <= 900, JSON.stringify(box));
  await page.locator('[data-testid="am-open-as"]').hover(); await wait(300);
  check('4 Open as shows a submenu with Private window', (await page.locator('[data-testid="am-as-private"]').count()) === 1);
  await page.locator('[data-testid="am-copy-link"]').click(); await wait(500);
  const clip = await page.evaluate(() => navigator.clipboard.readText());
  check('5 Copy link puts the full address on the clipboard', clip === `${base}/notes/${a.id}`, clip);
  check('6 and says so', /Link copied/.test(await page.locator('[data-testid="am-toast"]').innerText()));
  await row.click({ button: 'right' }); await wait(600);
  const [popup] = await Promise.all([ctx.waitForEvent('page', { timeout: 8000 }).catch(() => null), page.locator('[data-testid="am-open-tab"]').click()]);
  check('7 Open in new tab opens the note in another tab', !!popup && popup.url().includes(`/notes/${a.id}`), popup ? popup.url() : 'no tab');
  if (popup) await popup.close();
  await row.click({ button: 'right' }); await wait(800);
  await page.locator('[data-testid="am-pin"]').click(); await wait(900);
  const pinned = (await api('GET', `/api/notes/${a.id}`)).note;
  check('8 Pin pins the note', pinned.meta && pinned.meta.pinned === true, JSON.stringify(pinned.meta));
  await row.click({ button: 'right' }); await wait(800);
  await page.locator('[data-testid="am-inspect"]').click(); await wait(500);
  const dlg = await page.locator('[data-testid="am-details"]').innerText();
  check('9 Inspect shows the note details and its picture address', /Menu target note/.test(dlg) && /Words/.test(dlg) && /abcdef0123456789abcdef0123456789/.test(dlg), dlg.slice(0, 300));
  await page.keyboard.press('Escape'); await page.locator('[data-testid="am-details"] button[aria-label="Close"]').click().catch(() => {}); await wait(300);
  await page.locator('.bn-editor .bn-inline-content').first().click({ button: 'right' }); await wait(500);
  check('10 right-clicking inside the editor keeps the editor menu (no Peblo menu)', (await page.locator('[data-testid="app-menu"]').count()) === 0);
  await row.click({ button: 'right', modifiers: ['Shift'] }); await wait(500);
  check('11 Shift plus right-click leaves the browser menu alone', (await page.locator('[data-testid="app-menu"]').count()) === 0);
  await row.click({ button: 'right' }); await wait(600);
  await page.keyboard.press('Escape'); await wait(300);
  check('12 Escape closes the menu', (await page.locator('[data-testid="app-menu"]').count()) === 0);
  await row.click({ button: 'right' }); await wait(800);
  await page.locator('[data-testid="am-trash"]').click(); await wait(900);
  const gone = await api('GET', `/api/notes/${a.id}`).catch(() => null);
  check('13 Move to Trash trashes the note (it can be restored)', !gone || gone.note?.isDeleted === true || gone.note?.deletedAt, JSON.stringify(gone && gone.note && { d: gone.note.isDeleted }));
} catch (e) { check('crash: ' + e.message, false); }
await finish();
