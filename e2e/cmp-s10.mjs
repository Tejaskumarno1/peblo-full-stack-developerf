import { boot } from './lib.mjs';
const { base, api, ctx, finish } = await boot({ freshGuest: true });
const OUT = 'D:/Peblo/_shots';
const md = 'Three themes came up across the six client interviews: speed of delivery, clarity of briefs, and how corrections are handled.\n\n## 1. What we heard\n\nClients praise the team but ask for fewer rounds. Most delays start with an unclear first brief, not with the writing itself.\n\n| Theme | Evidence | Action |\n| --- | --- | --- |\n| Speed of delivery | Four of six interviews | Move reviews to Tuesday |\n\n## 2. Next steps\n\nWho signs off the final numbers, and by when?';
const note = (await api('POST', '/api/notes', { title: 'Q4 client report', content: md, tags: [] })).note;
const tok = (await api('POST', `/api/share/note/${note.id}`, { edit: true })).token;
const gc = await ctx.browser().newContext({ viewport: { width: 1440, height: 900 } });
await gc.addInitScript(() => { try { localStorage.setItem('peblo-guest-tour', '1'); } catch {} });
const g = await gc.newPage();
await g.goto(`${base}/s/note/${tok}`);
await g.locator('.bn-editor').waitFor({ timeout: 20000 });
await g.locator('[data-testid="join-card"]').getByLabel('Your name').fill('Priya');
await g.locator('[data-testid="join-submit"]').click();
await g.waitForTimeout(1500);
const sel = async (t) => { await g.locator('.bn-editor .bn-block-content', { hasText: t }).first().click({ clickCount: 3 }); await g.locator('[data-testid="comments-button"]').click(); };
await sel('unclear first brief');
const panel = g.locator('[data-testid="comments-panel"]');
await panel.locator('[data-testid="comment-on-selection"]').click();
await panel.locator('[data-testid="comment-text"]').fill('Can we name the two that disagreed?');
await panel.locator('[data-testid="comment-text"]').press('Enter');
await g.waitForTimeout(800);
await g.locator('.bn-editor .bn-block-content', { hasText: 'Who signs off' }).first().click({ clickCount: 3 });
await panel.locator('[data-testid="comment-on-selection"]').click().catch(() => {});
await g.waitForTimeout(600);
await g.screenshot({ path: `${OUT}/real-S10.png` });
await finish();
