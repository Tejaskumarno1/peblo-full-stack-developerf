// The notes drawer: a queue of notes to present through; the room follows along to public notes.
import { boot } from './lib.mjs';
const { base, api, page, ctx, check, finish } = await boot();
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const until = async (fn, ms = 12000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { try { if (await fn()) return true; } catch { /* retry */ } await wait(150); } return false; };
try {
  const mk = async (title) => (await api('POST', '/api/notes', { title, content: `# ${title}\n\nBody of ${title}`, tags: [] })).note;
  const A = await mk('Alpha'), B = await mk('Bravo'), C = await mk('Charlie');
  const tA = (await api('POST', `/api/share/note/${A.id}`, { edit: true })).token;
  const tB = (await api('POST', `/api/share/note/${B.id}`, { edit: true })).token;
  await page.goto(base + '/notes/' + A.id);
  const c = await ctx.browser().newContext({ viewport: { width: 1100, height: 800 } });
  const g = await c.newPage(); await g.goto(`${base}/s/note/${tA}`); await g.locator('.bn-editor').waitFor({ timeout: 20000 });
  await page.locator('[data-testid="present-btn"]').waitFor({ timeout: 20000 });
  await page.locator('[data-testid="present-btn"]').click();
  await page.getByTestId('pm-start').click();
  check('1 presenting', await until(async () => (await page.locator('[data-testid="present-btn"][aria-pressed="true"]').count()) === 1));
  await g.getByTestId('present-follow').click({ timeout: 15000 });
  check('2 the guest follows', await until(async () => (await g.getByTestId('follow-banner').count()) === 1));
  check('3 the dock offers the notes drawer', await until(async () => (await page.getByTestId('dock-queue').count()) === 1));
  await page.getByTestId('dock-queue').click();
  const dr = page.getByTestId('queue-drawer');
  check('4 the drawer opens with this note live', await dr.isVisible() && /Alpha/.test(await dr.getByTestId('queue-row').first().innerText()) && /Live/.test(await dr.innerText()));
  await dr.getByTestId('queue-search').fill('brav');
  check('5 search narrows the list', (await dr.getByTestId('queue-recent').count()) === 1);
  await dr.getByTestId('queue-search').fill('');
  await dr.getByTestId('queue-recent').filter({ hasText: 'Bravo' }).click();
  await dr.getByTestId('queue-recent').filter({ hasText: 'Charlie' }).click();
  check('6 recent notes join the queue', (await dr.getByTestId('queue-row').count()) === 3);
  check('7 chips say Public and Private', /Public/.test(await dr.getByTestId('queue-row').nth(1).innerText()) && /Private/.test(await dr.getByTestId('queue-row').nth(2).innerText()));
  await dr.getByTestId('queue-grip').nth(2).focus(); await page.keyboard.press('ArrowUp');
  check('8 the arrow keys reorder', await until(async () => /Charlie/.test(await dr.getByTestId('queue-row').nth(1).innerText())));
  await dr.getByTestId('queue-grip').nth(1).focus(); await page.keyboard.press('ArrowDown');
  check('9 and back again', await until(async () => /Bravo/.test(await dr.getByTestId('queue-row').nth(1).innerText())));
  check('10 the dock says Notes 1 of 3', /Notes 1 of 3/.test(await page.getByTestId('dock-queue').getAttribute('title')));
  await page.mouse.click(600, 400); await page.keyboard.press('n');
  check('11 N moves to the next note', await until(async () => page.url().includes('/notes/' + B.id)));
  check('12 still presenting there, drawer kept open', await until(async () => (await page.locator('[data-testid="present-btn"][aria-pressed="true"]').count()) === 1 && await page.getByTestId('queue-drawer').isVisible()));
  check('13 the dock says Notes 2 of 3', await until(async () => /Notes 2 of 3/.test(await page.getByTestId('dock-queue').getAttribute('title'))));
  check('14 the room followed to the same note', await until(async () => g.url().includes('/s/note/' + tB)));
  check('15 and keeps following', await until(async () => (await g.getByTestId('follow-banner').count()) === 1));
  await page.keyboard.press('p');
  check('16 P goes back', await until(async () => page.url().includes('/notes/' + A.id)));
  await page.getByTestId('queue-keep').uncheck({ force: true });
  await page.getByTestId('queue-row').filter({ hasText: 'Charlie' }).getByRole('button').first().click();
  check('17 a private note opens for the presenter', await until(async () => page.url().includes('/notes/' + C.id)));
  check('18 the room stays where it was', g.url().includes('/s/note/') && !g.url().includes('/s/note/' + tB));
} catch (e) { check('crash: ' + e.message, false); }
await finish();
