import { boot, REPO } from './lib.mjs';
const { base, api, page, finish } = await boot();
const shot = (n) => page.screenshot({ path: REPO + '/.shots/' + n + '.png', fullPage: false });
const errs = [];
page.on('pageerror', (e) => errs.push('pageerror: ' + String(e).slice(0, 160)));
page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text().slice(0, 160)); });
const a = (await api('POST', '/api/notes', { title: 'Weekly sync', content: '## Agenda\n\nSam will send the deck by Friday.\n\n- [ ] book room\n\n> 💡 idea\n\n' + 'Lorem ipsum dolor sit amet. '.repeat(40), tags: ['work', 'meeting'] })).note;
await api('POST', '/api/notes', { title: 'Old idea', content: 'Archived thing', tags: ['ideas'] }).then(async (r) => { await api('POST', `/api/notes/${r.note.id}/archive`).catch(() => {}); });
await api('POST', '/api/notes', { title: 'Trashed', content: 'bye', tags: [] }).then(async (r) => { await api('DELETE', `/api/notes/${r.note.id}`); });
await page.goto(base + '/');
await page.evaluate(() => localStorage.setItem('peblo-style', 'river'));
await page.goto(base + '/notes');
await page.locator('.r-list').waitFor({ timeout: 12000 });
await page.waitForTimeout(800);
await shot('rv-list');
await page.getByRole('button', { name: 'Archive' }).first().click();
await page.waitForTimeout(800);
console.log('ARCHIVE LIST buttons:', await page.locator('.r-list button').allInnerTexts());
await shot('rv-archive');
await page.getByRole('button', { name: 'Trash' }).first().click();
await page.waitForTimeout(800);
console.log('TRASH LIST buttons:', await page.locator('.r-list button').allInnerTexts());
await page.goto(base + `/notes/${a.id}`);
await page.locator('.bn-editor').waitFor({ timeout: 12000 });
await page.waitForTimeout(1200);
await shot('rv-note');
console.log('HEADER links:', await page.locator('.r-head a, .r-head button').allInnerTexts());
await page.getByRole('button', { name: 'More' }).click();
console.log('MENU:', await page.locator('.r-pop button').allInnerTexts());
await page.keyboard.press('Escape');
const tagBtn = page.locator('.r-tag').first();
await tagBtn.click().catch(() => {});
console.log('after clicking a tag chip, url:', page.url());
console.log('word count/outline on note page:', await page.locator('text=/\\d+ words/').count(), await page.locator('text=/outline/i').count());
await page.setViewportSize({ width: 420, height: 800 });
await page.waitForTimeout(600);
await shot('rv-note-mobile');
console.log('mobile h-scroll:', await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2));
await page.goto(base + '/notes');
await page.waitForTimeout(800);
await shot('rv-list-mobile');
console.log('mobile list h-scroll:', await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2));
console.log('ERRORS:', errs.slice(0, 8));
await finish();
