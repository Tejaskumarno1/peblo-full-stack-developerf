import { boot, REPO } from './lib.mjs';
const { base, api, page, finish } = await boot();
const shot = (n) => page.screenshot({ path: REPO + '/.shots/' + n + '.png' });
await page.setViewportSize({ width: 1440, height: 900 });
const today = new Date(); today.setHours(0, 0, 0, 0);
const iso = (d) => d.toISOString();
const add = (n) => { const d = new Date(today); d.setDate(d.getDate() + n); return d; };
const mk = (text, d, extra = {}) => api('POST', '/api/todos', { text, deadline: iso(d), priority: 'medium', ...extra });
await mk('Standup with design team', today, { startTime: '10:00', endTime: '10:30' });
await mk('Client call: Agile Digest', today, { startTime: '14:00', endTime: '15:00' });
await mk('Send weekly report', today, { priority: 'high' });
await mk('Review pull request', today);
await mk('Sprint planning', add(1), { startTime: '11:00', endTime: '12:00' });
await mk('Submit assignment', add(2), { priority: 'high' });
await api('POST', '/api/notes', { title: 'Weekly sync', content: '## Agenda\n\n- Release plan\n- Hiring', tags: ['meeting'] });
await page.goto(base + '/');
await page.evaluate(() => localStorage.setItem('peblo-style', 'river'));
await page.goto(base + '/');
await page.waitForTimeout(2500);
await shot('rv-home');
console.log('HEAD', await page.locator('.river').first().innerText().then((t) => t.slice(0, 600)));
await finish();
